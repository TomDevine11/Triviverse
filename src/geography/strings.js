export function t(key, vars) {
  let s = key.split('.').reduce((o, k) => (o == null ? undefined : o[k]), STRINGS)
  if (s == null) return key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v)
  return s
}

// A list of strings (e.g. how-to steps), each with {placeholders} filled.
export function tl(key, vars) {
  const list = key.split('.').reduce((o, k) => (o == null ? undefined : o[k]), STRINGS)
  if (!Array.isArray(list)) return []
  return list.map(s => (vars ? Object.entries(vars).reduce((a, [k, v]) => a.replaceAll(`{${k}}`, v), s) : s))
}
